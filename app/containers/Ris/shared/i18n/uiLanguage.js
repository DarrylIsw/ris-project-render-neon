export const normalizeUiLocale = locale => (locale === UI_LOCALE.EN ? UI_LOCALE.EN : UI_LOCALE.ID);

export const getStoredUiLocale = (userId, fallback) => {
  if (!userId || typeof window === 'undefined') return normalizeUiLocale(fallback);
  try {
    return normalizeUiLocale(window.localStorage.getItem(`ris-ui-locale:${userId}`) || fallback);
  } catch (error) {
    return normalizeUiLocale(fallback);
  }
};

export const persistUiLocale = (userId, locale) => {
  if (!userId || typeof window === 'undefined') return false;
  try {
    window.localStorage.setItem(`ris-ui-locale:${userId}`, normalizeUiLocale(locale));
    return true;
  } catch (error) {
    return false;
  }
};

export const translateUiText = (value, locale) => {
  if (typeof value !== 'string') return value;
  const normalizedLocale = normalizeUiLocale(locale);
  const trimmed = value.trim();
  if (!trimmed) return value;
  const dictionary = normalizedLocale === UI_LOCALE.EN ? idToEn : enToId;
  const translated = dictionary[trimmed] || translatePattern(trimmed, normalizedLocale);
  return translated === trimmed ? value : preserveWhitespace(value, translated);
};

const excludedElement = element => element && element.closest('script, style, textarea, pre, code, [data-ui-translation-skip], [data-ris-document-preview]');

const translateTextNode = (node, locale) => {
  if (!node || !node.parentElement || excludedElement(node.parentElement)) return;
  const textNode = node;
  const translated = translateUiText(textNode.nodeValue, locale);
  if (translated !== textNode.nodeValue) textNode.nodeValue = translated;
};

const translateAttributes = (element, locale) => {
  if (!element || excludedElement(element)) return;
  ['placeholder', 'title', 'aria-label'].forEach(attribute => {
    const value = element.getAttribute(attribute);
    if (value === null) return;
    const translated = translateUiText(value, locale);
    if (translated !== value) element.setAttribute(attribute, translated);
  });
};

const translateTree = (root, locale) => {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const textNodes = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode);
  textNodes.forEach(node => translateTextNode(node, locale));
  if (root.nodeType === Node.ELEMENT_NODE) translateAttributes(root, locale);
  root.querySelectorAll('*').forEach(element => translateAttributes(element, locale));
};

export default function UiLanguageLayer({ locale, rootRef }) {
  useEffect(() => {
    const root = rootRef.current;
    if (!root) return undefined;
    let scheduled = false;
    const translate = () => {
      scheduled = false;
      translateTree(root, locale);
    };
    const schedule = () => {
      if (scheduled) return;
      scheduled = true;
      Promise.resolve().then(translate);
    };
    translate();
    const observer = new MutationObserver(schedule);
    observer.observe(root, {
      childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label']
    });
    return () => observer.disconnect();
  }, [locale, rootRef]);

  return null;
}

UiLanguageLayer.propTypes = {
  locale: PropTypes.oneOf([UI_LOCALE.ID, UI_LOCALE.EN]).isRequired,
  rootRef: PropTypes.object.isRequired,
};
